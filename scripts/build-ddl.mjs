// Regenerates server/database/ddl.ts from the generated migration SQL.
//
// The demo runs on an in-process PGlite database that is created empty on every
// boot, so it has no migration history to apply — it just needs the schema as
// one blob of SQL. Keeping that blob in a .ts module means the server bundle
// carries it directly and never reads the migrations folder at runtime.
//
// Run after `npm run db:generate`.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const MIGRATIONS = 'server/database/migrations'
const OUT = 'server/database/ddl.ts'

const files = (await readdir(MIGRATIONS)).filter(f => f.endsWith('.sql')).sort()
if (files.length === 0) {
  throw new Error(`no .sql files in ${MIGRATIONS} — run \`npm run db:generate\` first`)
}

const sql = (await Promise.all(
  files.map(f => readFile(join(MIGRATIONS, f), 'utf8')),
)).join('\n').trim()

const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')

await writeFile(OUT, `/* eslint-disable */
// Generated by scripts/build-ddl.mjs from ${MIGRATIONS}. Do not edit by hand.
// Run \`npm run db:generate && npm run db:ddl\` after changing the Drizzle schema.
export const DDL = \`
${escaped}
\`
`)

console.log(`✅ ${OUT} written from ${files.length} migration file(s), ${sql.length} chars`)
